#!/usr/bin/env node
/**
 * Generate CSS custom-property sheets from sop/themes palettes.
 *
 * Project `sop/themes/` is a fork of the suite attachment — evolve palettes
 * and this script as needed. Wire the generated CSS into `web/` (do not hand-
 * edit palette values in app CSS).
 *
 * Usage (from project root after 000 seeds sop/themes/):
 *   node sop/themes/scripts/generate-theme-css.mjs
 *   node sop/themes/scripts/generate-theme-css.mjs --out web/src/styles/themes
 *   node sop/themes/scripts/generate-theme-css.mjs --sets web,ui --id innocent
 *
 * Options:
 *   --out DIR     Output directory (default: web/src/styles/themes)
 *   --sets LIST   Comma list: web,ui,erp,token (default: web)
 *   --id ID       Only emit one catalog id (default: all)
 *   --prefix P    CSS var prefix for non-web sets (default: set name)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const themesRoot = resolve(__dirname, '..');

function parseArgs(argv) {
    const opts = { out: 'web/src/styles/themes', sets: ['web'], id: null, prefix: null };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--out') opts.out = argv[++i];
        else if (a === '--sets') opts.sets = argv[++i].split(',').map((s) => s.trim()).filter(Boolean);
        else if (a === '--id') opts.id = argv[++i];
        else if (a === '--prefix') opts.prefix = argv[++i];
        else if (a === '-h' || a === '--help') {
            console.log(`Usage: node generate-theme-css.mjs [--out DIR] [--sets web,ui] [--id ID]`);
            process.exit(0);
        }
    }
    return opts;
}

function parseCatalog(tsvPath) {
    const lines = readFileSync(tsvPath, 'utf8').trim().split(/\r?\n/);
    const header = lines.shift().split('\t');
    return lines.map((line) => {
        const cols = line.split('\t');
        const row = {};
        header.forEach((h, i) => {
            row[h] = cols[i] ?? '';
        });
        return row;
    });
}

function cssEscapeIdent(name) {
    return name.replace(/[^a-zA-Z0-9_-]/g, '-');
}

function toCssVars(palette, { prefix = '' } = {}) {
    return Object.entries(palette)
        .map(([k, v]) => {
            const name = prefix ? `--${prefix}-${k}` : `--${k}`;
            return `  ${name}: ${v};`;
        })
        .join('\n');
}

async function loadGroupPalettes(group, set) {
    const file = join(themesRoot, group, `${set}-palettes.mjs`);
    if (!existsSync(file)) {
        throw new Error(`missing ${file}`);
    }
    const mod = await import(pathToFileURL(file).href);
    const key =
        set === 'web'
            ? 'webPalettes'
            : set === 'ui'
              ? 'uiPalettes'
              : set === 'erp'
                ? 'erpPalettes'
                : set === 'token'
                  ? 'tokenPalettes'
                  : null;
    if (!key || !mod[key]) {
        throw new Error(`${file} does not export ${key}`);
    }
    return mod[key];
}

function emitBlock(selector, body) {
    return `${selector} {\n${body}\n}\n`;
}

async function main() {
    const opts = parseArgs(process.argv.slice(2));
    const catalogPath = join(themesRoot, 'catalog.tsv');
    if (!existsSync(catalogPath)) {
        console.error('catalog.tsv not found under', themesRoot);
        process.exit(1);
    }

    const rows = parseCatalog(catalogPath).filter((r) => (opts.id ? r.id === opts.id : true));
    if (!rows.length) {
        console.error(opts.id ? `unknown catalog id: ${opts.id}` : 'catalog.tsv empty');
        process.exit(1);
    }

    const outDir = resolve(process.cwd(), opts.out);
    mkdirSync(outDir, { recursive: true });

    /** @type {Map<string, Record<string, any>>} */
    const cache = new Map();
    async function palettesFor(group, set) {
        const key = `${group}:${set}`;
        if (!cache.has(key)) {
            cache.set(key, await loadGroupPalettes(group, set));
        }
        return cache.get(key);
    }

    const indexLines = [
        '/* Generated by sop/themes/scripts/generate-theme-css.mjs — do not hand-edit. */',
        '/* Re-run after editing sop/themes palettes. Fork/customize the script as needed. */',
        '',
    ];

    for (const set of opts.sets) {
        const chunks = [
            `/* ${set} themes — generated from sop/themes */`,
            `/* Source: ${themesRoot} */`,
            '',
        ];
        for (const row of rows) {
            const map = await palettesFor(row.group, set);
            const pal = map[row.paletteKey];
            if (!pal) {
                console.warn(`skip ${row.id}: no ${set} paletteKey ${row.paletteKey} in ${row.group}/`);
                continue;
            }
            const prefix =
                set === 'web' ? '' : opts.prefix != null ? opts.prefix : set === 'token' ? 'tok' : set;
            const body = toCssVars(pal, { prefix });
            const sel = `[data-theme="${cssEscapeIdent(row.id)}"]`;
            chunks.push(`/* ${row.label} (${row.type}, ${row.group}) */`);
            chunks.push(emitBlock(sel, body));
            if (row.type === 'dark') {
                chunks.push(emitBlock(`${sel}.dark, .dark ${sel}`, body));
            }
        }
        const outFile = join(outDir, `themes-${set}.css`);
        writeFileSync(outFile, chunks.join('\n'));
        indexLines.push(`@import "./themes-${set}.css";`);
        console.log('wrote', outFile);
    }

    const indexPath = join(outDir, 'themes.css');
    writeFileSync(indexPath, indexLines.join('\n') + '\n');
    console.log('wrote', indexPath);
    console.log(`themes root: ${themesRoot}`);
    console.log(`variants: ${rows.length}; sets: ${opts.sets.join(',')}`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
