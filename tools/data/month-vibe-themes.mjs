/**
 * Calendar month vibe themes (January–December).
 * Each month anchors to a representative country, then picks seasonal /
 * festival color language (light + dark). Merged into vibe via
 * extra-aesthetic-ui.mjs + theme-catalog-prose.mjs.
 */

/** @typedef {Record<string, string>} UiPalette */

/**
 * @param {{
 *   windowBg: string, windowFg: string, windowShadow?: string,
 *   panelBg: string, surfaceBg: string, mutedFg?: string,
 *   actionFg: string, footerFg?: string, promptBg: string, promptFg?: string,
 *   intervalBg: string, intervalFg: string,
 *   quoteBg: string, quoteShadow: string, quoteGlow: string, quoteText: string,
 *   ratingLabel?: string, cardBg: string, selectedBg: string, todayBg: string,
 *   grid: string, border: string, weekdayHeader: string, chartHighlight: string,
 *   listFg?: string, gitModified: string, gitDeleted: string, gitUntracked: string,
 * }} s
 * @returns {UiPalette}
 */
function fillUi(s) {
    const fg = s.windowFg;
    return {
        windowBg: s.windowBg,
        windowFg: fg,
        windowShadow: s.windowShadow || s.border,
        panelBg: s.panelBg,
        surfaceBg: s.surfaceBg,
        mutedFg: s.mutedFg || fg,
        actionFg: s.actionFg,
        footerFg: s.footerFg || fg,
        promptBg: s.promptBg,
        promptFg: s.promptFg || fg,
        intervalBg: s.intervalBg,
        intervalFg: s.intervalFg,
        quoteBg: s.quoteBg,
        quoteShadow: s.quoteShadow,
        quoteGlow: s.quoteGlow,
        quoteText: s.quoteText,
        ratingLabel: s.ratingLabel || s.weekdayHeader,
        ratingTrack: s.panelBg,
        ratingKnobRing: s.border,
        ratingKnobFill: s.surfaceBg,
        ratingKnobCover: s.promptBg,
        ratingMarkerInactive: s.grid,
        ratingMarkerActive: s.actionFg,
        cardBg: s.cardBg,
        selectedBg: s.selectedBg,
        todayBg: s.todayBg,
        grid: s.grid,
        border: s.border,
        weekdayHeader: s.weekdayHeader,
        chartHighlight: s.chartHighlight,
        listFg: s.listFg || fg,
        gitModified: s.gitModified,
        gitDeleted: s.gitDeleted,
        gitUntracked: s.gitUntracked,
    };
}

