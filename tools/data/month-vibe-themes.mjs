function monthFamily(name, countryEn, countryZh, themeEn, themeZh, lightEn, lightZh, darkEn, darkZh) {
    const key = name.toLowerCase();
    const darkKey = `dark${name}`;
    return {
        group: 'vibe',
        meaning_en: `${name} — ${countryEn}: ${themeEn}`,
        meaning_zh: `${name}（${countryZh}）——${themeZh}`,
        variants: [
            {
                id: `light-${key}`,
                label: `Light ${name}`,
                type: 'light',
                paletteKey: key,
                en: lightEn,
                zh: lightZh,
            },
            {
                id: `dark-${key}`,
                label: `Dark ${name}`,
                type: 'dark',
                paletteKey: darkKey,
                en: darkEn,
                zh: darkZh,
            },
        ],
    };
}

