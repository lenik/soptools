/**
 * Extra country UI palettes for zfr L2 locales not in classic minor-themes.
 * Cultural color language — not national flags.
 *
 * Locales covered here:
 *   fr→France, es_MX→Mexico, ko→Korea, ar→Arab,
 *   id→Indonesia, nl→Netherlands, pl→Poland, tr→Turkey
 *
 * (it/de/zh_CN/ja/vi/th/pt_BR/ru/hi already have country packs.)
 */

/** Expand a compact seed into a full UiTheme-style 34-key HSL palette. */
export function expandUiSeed(seed) {
    const {
        windowBg,
        windowFg,
        panelBg,
        surfaceBg,
        mutedFg,
        actionFg,
        accentBg,
        accentFg,
        border,
        success,
        danger,
        warning,
        isDark,
    } = seed;
    const panel = panelBg || windowBg;
    const surface = surfaceBg || windowBg;
    const muted = mutedFg || windowFg;
    const action = actionFg;
    const sel = accentBg || panel;
    const selFg = accentFg || windowFg;
    const bord = border || muted;
    return {
        windowBg,
        windowFg,
        windowShadow: isDark ? 'hsl(0, 0%, 4%)' : muted,
        panelBg: panel,
        surfaceBg: surface,
        mutedFg: muted,
        actionFg: action,
        footerFg: muted,
        promptBg: isDark ? panel : surface,
        promptFg: windowFg,
        intervalBg: sel,
        intervalFg: selFg,
        quoteBg: isDark ? panel : surface,
        quoteShadow: bord,
        quoteGlow: action,
        quoteText: windowFg,
        ratingLabel: muted,
        ratingTrack: panel,
        ratingKnobRing: bord,
        ratingKnobFill: surface,
        ratingKnobCover: panel,
        ratingMarkerInactive: bord,
        ratingMarkerActive: action,
        cardBg: isDark ? panel : surface,
        selectedBg: sel,
        todayBg: sel,
        grid: bord,
        border: bord,
        weekdayHeader: selFg,
        chartHighlight: action,
        listFg: windowFg,
        gitModified: warning || action,
        gitDeleted: danger || action,
        gitUntracked: success || action,
    };
}

function hsl(h, s, l) {
    return `hsl(${h}, ${s}%, ${l}%)`;
}

